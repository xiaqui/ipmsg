package com.xiaqui.ipmsg

import org.json.JSONObject
import org.junit.Assert.assertEquals
import org.junit.Test
import org.junit.runner.RunWith
import org.robolectric.RobolectricTestRunner
import org.robolectric.annotation.Config
import java.security.KeyFactory
import java.security.KeyPair
import java.security.KeyPairGenerator
import java.security.spec.PKCS8EncodedKeySpec
import java.security.spec.RSAPrivateCrtKeySpec
import java.security.spec.RSAPublicKeySpec
import java.util.Base64

@RunWith(RobolectricTestRunner::class)
@Config(sdk=[34])
class WindowsInteropTest {
    private fun privateKey(pem: String) = KeyFactory.getInstance("RSA").generatePrivate(
        PKCS8EncodedKeySpec(Base64.getDecoder().decode(pem.replace("-----BEGIN PRIVATE KEY-----","")
            .replace("-----END PRIVATE KEY-----","").replace(Regex("\\s"),""))))

    private fun pair(pem: String): KeyPair {
        val private=privateKey(pem)
        val spec=KeyFactory.getInstance("RSA").getKeySpec(private,RSAPrivateCrtKeySpec::class.java)
        val public=KeyFactory.getInstance("RSA").generatePublic(RSAPublicKeySpec(spec.modulus,spec.publicExponent))
        return KeyPair(public,private)
    }

    private fun pem(pair: KeyPair): String = "-----BEGIN PRIVATE KEY-----\n" +
        Base64.getMimeEncoder(64,"\n".toByteArray()).encodeToString(pair.private.encoded) +
        "\n-----END PRIVATE KEY-----\n"

    @Test fun windowsFixtureIsAcceptedByAndroidV1() {
        val text=javaClass.classLoader!!.getResourceAsStream("protocol-v1-windows-vector.json")!!
            .bufferedReader().use { it.readText() }
        val vector=JSONObject(text)
        val hello=Protocol.readHello(vector.getString("hello").toByteArray(),vector.getLong("now"))
        assertEquals(vector.getString("senderId"),hello.id)
        val sender=pair(vector.getString("senderPrivateTestOnly"))
        val recipient=pair(vector.getString("recipientPrivateTestOnly"))
        val body=Protocol.open(vector.getString("textFrame").toByteArray(),recipient,sender.public)
        assertEquals("TEXT",body.getString("type"));assertEquals(vector.getString("messageId"),body.getString("id"))
        assertEquals("Android ↔ Windows 日本語",body.getString("body"))
    }

    @Test fun androidGeneratesVectorsForWindows() {
        val sender=KeyPairGenerator.getInstance("RSA").apply { initialize(2048) }.generateKeyPair()
        val recipient=KeyPairGenerator.getInstance("RSA").apply { initialize(2048) }.generateKeyPair()
        val now=1800000001000L
        val id="00000000-0000-0000-0000-000000000006"
        val text=Protocol.seal(JSONObject().put("type","TEXT").put("id",id)
            .put("body","Android生成 → Windows検証"),sender,recipient.public)
        val ack=Protocol.seal(JSONObject().put("type","ACK").put("id",id),recipient,sender.public)
        val vector=JSONObject().put("warning","TEST KEYS ONLY - GENERATED BY ANDROID Protocol")
            .put("now",now).put("messageId",id).put("senderId",Protocol.id(sender.public))
            .put("recipientId",Protocol.id(recipient.public)).put("senderPrivateTestOnly",pem(sender))
            .put("recipientPrivateTestOnly",pem(recipient))
            .put("hello",String(Protocol.hello("Android テスト",sender,now),Charsets.UTF_8))
            .put("textFrame",String(text,Charsets.UTF_8)).put("ackFrame",String(ack,Charsets.UTF_8))
        val root=System.getenv("GITHUB_WORKSPACE")?.let { java.io.File(it) } ?: java.io.File("build")
        val output=java.io.File(root,"build/interop/android-generated.json")
        output.parentFile.mkdirs();output.writeText(vector.toString(),Charsets.UTF_8)
    }
}

